package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"strings"
	"text/tabwriter"

	"github.com/veter/omnislash"
)

type stringList []string

func (s *stringList) String() string { return strings.Join(*s, ", ") }

func (s *stringList) Set(v string) error {
	*s = append(*s, v)
	return nil
}

func cmdScrape(args []string) error {
	fs := flag.NewFlagSet("scrape", flag.ContinueOnError)
	common := addCommonFlags(fs)
	common.allowEmptyProxies = true
	var sources stringList
	fs.Var(&sources, "source", "URL источника (можно повторять; заменяет scraper.sources)")
	sourceScheme := fs.String("scheme", "http", "схема для записей host:port без схемы")
	jsonOut := fs.Bool("json", false, "вывести JSON")
	writePath := fs.String("write", "", "записать принятые прокси в файл")
	noValidate := fs.Bool("no-validate", false, "не проверять прокси (небезопасно)")
	maxCandidates := fs.Int("max", 0, "максимум кандидатов на проверку (переопределяет конфиг)")
	if err := fs.Parse(args); err != nil {
		return err
	}

	cfg, proxies, logger, err := common.load()
	if err != nil {
		return err
	}
	cfg.Scraper.Enabled = true
	if len(sources) > 0 {
		cfg.Scraper.Sources = make([]omnislash.SourceConfig, 0, len(sources))
		for _, raw := range sources {
			cfg.Scraper.Sources = append(cfg.Scraper.Sources, omnislash.SourceConfig{
				URL:    raw,
				Type:   "text",
				Scheme: *sourceScheme,
			})
		}
	}
	if len(cfg.Scraper.Sources) == 0 {
		return fmt.Errorf("нет источников: добавь scraper.sources в конфиг или используй -source URL")
	}
	if *noValidate {
		cfg.Scraper.Validation.Enabled = false
	}
	if *maxCandidates > 0 {
		cfg.Scraper.MaxCandidates = *maxCandidates
	}
	if err := cfg.Validate(); err != nil {
		return err
	}

	pool, err := omnislash.NewPool(cfg, proxies, logger)
	if err != nil {
		return err
	}
	scraper, err := omnislash.NewScraper(pool, cfg.Scraper, logger)
	if err != nil {
		return err
	}

	ctx, stop := signalContext()
	defer stop()

	stats, refreshErr := scraper.Refresh(ctx)
	if *jsonOut {
		out := struct {
			Scraper omnislash.ScraperStats `json:"scraper"`
			Pool    omnislash.Stats        `json:"pool"`
		}{Scraper: stats, Pool: pool.Stats()}
		enc := json.NewEncoder(os.Stdout)
		enc.SetIndent("", "  ")
		if err := enc.Encode(out); err != nil {
			return err
		}
	} else {
		fmt.Printf("Источников: %d, ошибок источников: %d\n", stats.Sources, stats.SourceErrors)
		fmt.Printf("Кандидатов: %d, проверено: %d, принято: %d, отклонено: %d\n",
			stats.Candidates, stats.Validated, stats.Accepted, stats.Rejected)
		w := tabwriter.NewWriter(os.Stdout, 0, 4, 2, ' ', 0)
		fmt.Fprintln(w, "ПРОКСИ\tEGRESS\tПРОВЕРКА")
		for _, ps := range pool.Stats().Proxies {
			lat := "-"
			if ps.ValidationLatencyMS > 0 {
				lat = fmt.Sprintf("%.0fms", ps.ValidationLatencyMS)
			}
			fmt.Fprintf(w, "%s\t%s\t%s\n", ps.Proxy, emptyDash(ps.EgressIP), lat)
		}
		_ = w.Flush()
	}

	if refreshErr != nil {
		return refreshErr
	}
	if *writePath != "" {
		if err := writeProxyFile(*writePath, pool.Proxies()); err != nil {
			return err
		}
		fmt.Printf("Записано %d прокси в %s\n", len(pool.Proxies()), *writePath)
	}
	return nil
}

func writeProxyFile(path string, proxies []*omnislash.Proxy) error {
	var b strings.Builder
	b.WriteString("# generated by omnislash scrape\n")
	for _, pr := range proxies {
		b.WriteString(pr.String())
		b.WriteByte('\n')
	}
	return os.WriteFile(path, []byte(b.String()), 0o600)
}

func emptyDash(v string) string {
	if v == "" {
		return "-"
	}
	return v
}
